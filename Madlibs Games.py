# Madlibs Game
adjective1=input("Enter an adjective: ")
noun1=input("Enter a noun: ")
adjective2=input("Enter another adjective: ")
verb1=input("Enter a verb: ")
adjective3=input("Enter another adjective: ")

print(f"Once upon a time, there was a {adjective1} {noun1} that loved to {verb1}.")
print(f"It was a {adjective2} day, and the {noun1} felt very {adjective3}.")
print("It decided to go on an adventure to find more {adjective1} things.")
print(f"Along the way, it met a {adjective2} creature that also loved to {verb1}.")
print("They became friends and continued their journey together.")
print(f"Together, they discovered a {adjective3} land filled with {noun1}s.")